function CredentialsModal({ title, user, password, onClose }: { title: string; user: ManagedUser; password: string; onClose: () => void }) {
  const [copied, setCopied] = useState(false);

  const copy = async () => {
    try {
      await navigator.clipboard.writeText(`Email: ${user.email}\nTemporary password: ${password}`);
      setCopied(true);
    } catch {
      /* clipboard blocked: the values are visible to copy by hand */
    }
  };

  return (
    <Modal title={title} onClose={onClose}>
      <div className="space-y-4 text-sm">
        <p className="text-slate-600">
          Share these with <span className="font-medium text-slate-800">{user.name}</span>. The password is shown only now, and they'll be asked to change it at first login.
        </p>
        <div className="space-y-2 rounded-lg bg-slate-50 p-4 font-mono text-sm">
          <p><span className="text-slate-500">Email: </span>{user.email}</p>
          <p><span className="text-slate-500">Password: </span>{password}</p>
        </div>
        <div className="flex justify-end gap-3">
          <button onClick={copy} className="flex items-center gap-2 rounded-lg border border-slate-200 px-4 py-2 font-medium text-slate-700 hover:bg-slate-50">
            <Copy size={15} /> {copied ? "Copied" : "Copy"}
          </button>
          <button onClick={onClose} className="rounded-lg bg-blue-600 px-5 py-2 font-medium text-white hover:bg-blue-700">Done</button>
        </div>
      </div>
    </Modal>
  );
}

